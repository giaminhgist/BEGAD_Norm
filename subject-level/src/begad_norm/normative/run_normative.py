"""BEGAD normative-model runner — runs every (problem, seed, fold) job.

Protocol (see config.yaml and docs/plans/2026-10-14-normative-model.md):
  - model: learned normative-deviation pipeline (mlp_deepset port of LNGModel
    EXP-PROP-001); one sample per participant, 25 features x 11 tasks
    (missing cells filled with the train-fold per-feature mean, standardized
    per fold on the training split; all-NaN tasks masked).
  - CV: participant-level stratified by group, 5 folds, 20 seeds — folds
    generated by the SAME function as the baseline
    (begad_norm.baseline.run_baselines.stratified_folds), so the results are
    directly comparable with outputs/baseline_balanced.
  - problems: co_vs_mci (MCI positive), co_vs_ad (AD positive), co_mci_ad
    (3-class; Sen/Precision/Spec/F1 macro, AUC macro OVR).
  - one detail row per evaluation with the baseline schema.

Usage:
    python -m begad_norm.normative.run_normative --config src/begad_norm/normative/config.yaml --smoke
    python -m begad_norm.normative.run_normative --config src/begad_norm/normative/config.yaml --workers 8
    python -m begad_norm.normative.run_normative --config src/begad_norm/normative/config.yaml \
        --problems co_vs_mci --seeds 1,2 --folds 1

Reproducibility: config + seeds + data-file hashes + code hash + environment
are written to outputs/normative/provenance.json and each run's run_info.json.
Resume-safe: a job is skipped only when its run dir has a completed
summary.json AND the recorded code/data hashes match the current files.
"""
import argparse
import csv
import hashlib
import importlib.metadata
import json
import platform
import socket
import subprocess
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import torch
import yaml

from begad_norm.config import PROJECT_ROOT
from begad_norm.normative.data import NormativeDataset
from begad_norm.normative.model import NormativeModel
from begad_norm.normative.seeding import code_hash, determinism_env_info
from begad_norm.normative.trainer import NormativeConfig, train_model
from begad_norm.baseline.run_baselines import stratified_folds

METRIC_COLS = ["acc", "sen", "precision", "spec", "auc", "f1"]
DETAIL_COLS = ["dataset", "problem", "model", "seed", "fold", "n_train",
               "n_test"] + METRIC_COLS


def load_config(path):
    cfg = yaml.safe_load(Path(path).read_text())
    cfg["config_path"] = str(Path(path).resolve())
    cfg["config_sha256"] = sha256_file(Path(path))
    return cfg


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def data_hashes(cfg):
    """sha256 of the data files that define the feature schema/content."""
    out = {}
    for ds in cfg["data"]["datasets"]:
        for key in ("features_csv", "metadata_csv"):
            out[ds["name"] + "/" + key] = sha256_file(PROJECT_ROOT / ds[key])
    return out


def _git_commit():
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True,
            cwd=PROJECT_ROOT, check=False).stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def jobs_from_config(cfg, problems=None, seeds=None, folds=None):
    """All (problem, seed, fold) jobs; filters mirror the baseline runner."""
    jobs = []
    for problem in cfg["problems"]:
        if problems and problem["name"] not in problems:
            continue
        for seed in cfg["cv"]["seeds"]:
            if seeds is not None and seed not in seeds:
                continue
            for fold in range(1, cfg["cv"]["n_folds"] + 1):
                if folds is not None and fold not in folds:
                    continue
                jobs.append({"problem": problem["name"], "seed": seed,
                             "fold": fold})
    return jobs


def _job_cfg(cfg, job, epochs_override=None):
    n_classes = 3 if job["problem"] == "co_mci_ad" else 1
    return NormativeConfig(
        experiment=cfg["experiment"]["name"],
        problem=job["problem"], model=cfg["model"]["name"],
        seed=job["seed"], fold=job["fold"],
        epochs=epochs_override or cfg["training"]["epochs"],
        patience=cfg["training"]["patience"], lr=cfg["training"]["lr"],
        weight_decay=cfg["training"]["weight_decay"],
        batch_size=cfg["training"]["batch_size"],
        dropout=cfg["model"]["dropout"], n_classes=n_classes,
        out_root=str(PROJECT_ROOT / cfg["output"]["dir"]))


def _run_job(args):
    """Worker: one (problem, seed, fold) training run (picklable, per-process)."""
    job, cfg_dict, run_cfg, dataset_cfg = args
    torch.set_num_threads(1)  # workers run in parallel; avoid oversubscription
    cfg = NormativeConfig.from_dict(cfg_dict)
    features_csv = PROJECT_ROOT / dataset_cfg["features_csv"]
    metadata_csv = PROJECT_ROOT / dataset_cfg["metadata_csv"]
    meta = pd.read_csv(metadata_csv).set_index("participant_id")
    # fold assignment: SAME method as the baseline, over the problem's groups
    from begad_norm.normative.data import PROBLEMS
    groups = PROBLEMS[job["problem"]]["groups"]
    pid_group = {pid: meta.loc[pid, "group_label"]
                 for pid in meta.index if meta.loc[pid, "group_label"] in groups}
    assign = stratified_folds(pid_group, job["seed"], run_cfg["cv"]["n_folds"])
    train_pids = sorted(p for p, f in assign.items() if f != job["fold"])
    val_pids = sorted(p for p, f in assign.items() if f == job["fold"])
    ds_tr = NormativeDataset(train_pids, train_pids, features_csv, metadata_csv,
                             job["problem"], run_cfg["data"]["n_tasks"])
    ds_va = NormativeDataset(val_pids, train_pids, features_csv, metadata_csv,
                             job["problem"], run_cfg["data"]["n_tasks"])
    n_classes = cfg.n_classes
    factory = lambda: NormativeModel(
        d_in=run_cfg["model"]["d_in"],
        latent_dim=run_cfg["model"]["latent_dim"],
        dev_dim=run_cfg["model"]["dev_dim"],
        comparator=run_cfg["model"]["comparator"],
        pool=run_cfg["model"]["pool"],
        dropout=run_cfg["model"]["dropout"],
        n_stim=run_cfg["data"]["n_tasks"], n_classes=n_classes)
    summary = train_model(factory, ds_tr, ds_va, cfg, "cpu",
                          run_info={"data": data_hashes(run_cfg)})
    row = {"dataset": dataset_cfg["name"], "problem": job["problem"],
           "model": run_cfg["model"]["name"], "seed": job["seed"],
           "fold": job["fold"], "n_train": len(train_pids),
           "n_test": len(val_pids)}
    for m in METRIC_COLS:
        row[m] = summary["best_val_metrics"][m]
    return {"row": row, "status": "completed",
            "best_epoch": summary["best_epoch"],
            "stopping_reason": summary["stopping_reason"]}


def _resume_key(row_dict):
    return (row_dict["problem"], row_dict["seed"], row_dict["fold"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="src/begad_norm/normative/config.yaml")
    ap.add_argument("--smoke", action="store_true",
                    help="1 problem x 1 seed x 1 fold, 5 epochs")
    ap.add_argument("--problems", default="",
                    help="comma-separated problem filter (default: all)")
    ap.add_argument("--seeds", default="",
                    help="comma-separated seed filter (default: all)")
    ap.add_argument("--folds", default="",
                    help="comma-separated fold filter (default: all)")
    ap.add_argument("--workers", type=int, default=8)
    args = ap.parse_args()

    cfg = load_config(args.config)
    if args.smoke:
        # smoke runs (5 epochs) must not pollute the real matrix's outputs
        cfg["output"]["dir"] = "outputs/normative_smoke"
    out_root = PROJECT_ROOT / cfg["output"]["dir"]
    results_dir = out_root / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    detail_path = out_root / cfg["output"]["detail_csv"]
    detail_path.parent.mkdir(parents=True, exist_ok=True)

    problems = [p for p in args.problems.split(",") if p] or None
    seeds = [int(s) for s in args.seeds.split(",") if s] or None
    folds = [int(f) for f in args.folds.split(",") if f] or None
    if args.smoke:
        problems = ["co_vs_mci"]
        seeds = [42]
        folds = [1]

    jobs = jobs_from_config(cfg, problems, seeds, folds)
    n_total = len(jobs)
    if n_total == 0:
        sys.exit("no jobs match the filters")

    # resume: rows already present in the detail file are not re-run
    existing = set()
    if detail_path.exists():
        with open(detail_path, newline="") as f:
            for row in csv.DictReader(f):
                existing.add((row["problem"], int(row["seed"]), int(row["fold"])))
    hashes = data_hashes(cfg)
    code = code_hash()
    pending = []
    for job in jobs:
        key = (job["problem"], job["seed"], job["fold"])
        if key in existing:
            continue
        run_dir = _job_cfg(cfg, job).run_dir(create=False)
        if (run_dir / "summary.json").exists() and \
                (run_dir / "run_info.json").exists():
            info = json.loads((run_dir / "run_info.json").read_text())
            if info.get("status") == "completed" and \
                    info.get("code_hash") == code and \
                    info.get("data") == hashes:
                continue  # resume-safe skip: artifacts complete + hashes match
        pending.append(job)
    n_skip = n_total - len(pending)
    print(f"{len(pending)} jobs to run ({n_skip} already recorded)")

    write_header = not detail_path.exists() or detail_path.stat().st_size == 0
    run_log_path = out_root / cfg["output"]["run_log_csv"]
    started = time.strftime("%Y-%m-%d %H:%M:%S")

    n_ok, n_fail = 0, 0
    with open(detail_path, "a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=DETAIL_COLS)
        if write_header:
            writer.writeheader()
            f.flush()
        if args.smoke:
            run_cfg = dict(cfg)
            run_cfg["training"] = dict(cfg["training"], epochs=5)
        else:
            run_cfg = cfg
        task_args = [(
            job, _job_cfg(cfg, job, epochs_override=5 if args.smoke else None
                          ).to_dict(), run_cfg, cfg["data"]["datasets"][0])
            for job in pending]
        if len(task_args) == 1 or args.workers <= 1:
            results = [_run_job(a) for a in task_args]
        else:
            results = []
            with ProcessPoolExecutor(max_workers=args.workers) as ex:
                futs = {ex.submit(_run_job, a): a[0] for a in task_args}
                for fut in as_completed(futs):
                    try:
                        results.append(fut.result())
                    except Exception as exc:  # keep going; record the failure
                        job = futs[fut]
                        results.append({"row": {
                            "dataset": cfg["data"]["datasets"][0]["name"],
                            "problem": job["problem"], "model": cfg["model"]["name"],
                            "seed": job["seed"], "fold": job["fold"],
                            "n_train": None, "n_test": None,
                            **{m: None for m in METRIC_COLS}},
                            "status": f"failed: {exc}"})
        for r in results:
            if r["status"] == "completed":
                writer.writerow(r["row"])
                f.flush()
                n_ok += 1
            else:
                n_fail += 1
            with open(run_log_path, "a", newline="") as lf:
                w = csv.writer(lf)
                if run_log_path.stat().st_size == 0:
                    w.writerow(["problem", "seed", "fold", "status",
                                "best_epoch", "stopping_reason", "timestamp"])
                w.writerow([r["row"]["problem"], r["row"]["seed"],
                            r["row"]["fold"], r["status"],
                            r.get("best_epoch", ""),
                            r.get("stopping_reason", ""),
                            time.strftime("%Y-%m-%d %H:%M:%S")])

    provenance = {
        "config_path": cfg["config_path"],
        "config_sha256": cfg["config_sha256"],
        "data_hashes": hashes,
        "code_hash": code,
        "env": determinism_env_info(),
        "git_commit": _git_commit(),
        "platform": platform.platform(),
        "host": socket.gethostname(),
        "python_pkgs": {k: importlib.metadata.version(k)
                        for k in ("torch", "numpy", "pandas", "scikit-learn")},
        "n_jobs": {"total": n_total, "skipped_existing": n_skip,
                   "completed": n_ok, "failed": n_fail},
        "started": started,
        "finished": time.strftime("%Y-%m-%d %H:%M:%S"),
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
    }
    (out_root / cfg["output"]["provenance_file"]).write_text(
        json.dumps(provenance, indent=2))
    print(f"done: {n_ok} completed, {n_fail} failed, {n_skip} already recorded")
    if n_fail:
        sys.exit(1)


if __name__ == "__main__":
    main()
